"""Replay field-level scalar contrasts without implying raster regeneration."""

import math
from collections import defaultdict
from pathlib import Path

from .adapters import result_directory, verified_tables
from .analysis import paired_change, sign_discordance


def reproduce(directory: Path | None = None) -> dict[str, object]:
    """Recalculate means and sign counts; retained intervals are not rerun."""
    tables = verified_tables(directory or result_directory())
    groups: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in tables["field_contrasts.csv"]:
        groups[row["cohort"], row["pair"]].append(row)
    effects = []
    for expected in tables["paired_effects.csv"]:
        rows = groups[expected["cohort"], expected["pair"]]
        if len({row["sample_id"] for row in rows}) != len(rows):
            raise ValueError("Repeated field identity in a fixed comparison roster")
        calculated = paired_change(
            [float(row["all_contrast"]) for row in rows],
            [float(row["survivor_contrast"]) for row in rows],
        )
        for key, source in [
            ("mean_all_contrast", "all_contrast"),
            ("mean_survivor_contrast", "survivor_contrast"),
            ("mean_change", "mean_change"),
        ]:
            if not math.isclose(calculated[key], float(expected[source]), abs_tol=1e-13):
                raise ValueError(f"Scalar replay mismatch: {expected['cohort']} {source}")
        if len(rows) != int(expected["n"]):
            raise ValueError("Field denominator mismatch")
        effects.append({"cohort": expected["cohort"], "pair": expected["pair"], **calculated})
    margins = 0
    for expected in tables["margin_sensitivity.csv"]:
        rows = groups[expected["cohort"], expected["pair"]]
        calculated_counts = sign_discordance(
            [float(row["all_contrast"]) for row in rows],
            [float(row["survivor_contrast"]) for row in rows],
            float(expected["epsilon"]),
        )
        for actual, source in [
            ("common_count", "common_n"),
            ("qualified_count", "both_exceed_margin_n"),
            ("opposite_count", "opposite_n"),
        ]:
            if calculated_counts[actual] != int(expected[source]):
                raise ValueError(f"Margin replay mismatch: {actual}")
        margins += 1
    return {
        "scope": "Saved scalar field contrasts only; no inference, training or raw-mask replay",
        "paired_effects": effects,
        "margin_rows_verified": margins,
        "canonical_tables_integrity_verified": len(tables),
        "intervals": "Preserved published-candidate bootstrap outputs, not regenerated by this command",
    }
